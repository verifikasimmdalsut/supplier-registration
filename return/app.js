/* =========================
   ELEMENT
========================= */

const supplierSection =
  document.getElementById("supplierSection");

const detailSection =
  document.getElementById("detailSection");

const supplierList =
  document.getElementById("supplierList");

const supplierCount =
  document.getElementById("supplierCount");

const searchInput =
  document.getElementById("searchSupplier");


/* =========================
   GROUP SUPPLIER
========================= */

function groupBySupplier(data){

  const result = {};

  data.forEach(row => {

    const code = String(row.supplierCode);

    if(!result[code]){

      result[code] = {
        code: code,
        name: row.supplier,
        rows: []
      };

    }

    result[code].rows.push(row);

  });

  return Object.values(result);

}


/* =========================
   HITUNG SLIP
========================= */

function countSlip(rows){

  return new Set(
    rows.map(row => String(row.returnNo))
  ).size;

}


/* =========================
   TAMPIL SUPPLIER
========================= */

function renderSuppliers(data){

  const suppliers =
    groupBySupplier(data);

  supplierCount.textContent =
    suppliers.length + " Supplier";


  supplierList.innerHTML =
    suppliers.map(supplier => {

      const slipCount =
        countSlip(supplier.rows);

      return `

        <div
          class="supplier-card"
          onclick="openSupplier('${supplier.code}')"
        >

          <div class="supplier-name">
            ${supplier.name}
          </div>

          <div class="supplier-code">
            Kode Supplier: ${supplier.code}
          </div>

          <div class="slip-number">
            ${slipCount}
          </div>

          <div class="slip-label">
            Slip Return
          </div>

          <div class="arrow">
            ›
          </div>

        </div>

      `;

    }).join("");

}


/* =========================
   GROUP SLIP
========================= */

function groupBySlip(rows){

  const result = {};

  rows.forEach(row => {

    const slip =
      String(row.returnNo);

    if(!result[slip]){
      result[slip] = [];
    }

    result[slip].push(row);

  });

  return result;

}


/* =========================
   STATUS
========================= */

function statusBadge(status){

  if(status === "UPDATED"){

    return `
      <span class="status-updated">
        UPDATED
      </span>
    `;

  }

  return `
    <span class="status-cancel">
      ${status}
    </span>
  `;

}


/* =========================
   BUKA DETAIL SUPPLIER
========================= */

function openSupplier(code){

  const supplier =
    groupBySupplier(RETURN_DATA)
      .find(item =>
        item.code === String(code)
      );


  if(!supplier){

    alert("Supplier tidak ditemukan");

    return;

  }


  const slipGroups =
    groupBySlip(supplier.rows);


  let html = `

    <div class="slip-title">

      DAFTAR SLIP RETURN

      <span style="
        float:right;
        color:#777;
        font-weight:normal;
        font-size:11px;
      ">
        ${Object.keys(slipGroups).length} Slip
      </span>

    </div>

  `;


  Object.entries(slipGroups)
    .forEach(([slipNo, items]) => {

      const first =
        items[0];


      html += `

        <div class="slip-card">

          <div
            class="slip-head"
            onclick="toggleSlip(this)"
          >

            <div class="slip-no">
              No. Slip: ${slipNo}
            </div>

            <div class="meta">
              Tanggal
              <strong>
                ${first.date}
              </strong>
            </div>

            <div class="meta">
              Status
              <strong>
                ${statusBadge(first.status)}
              </strong>
            </div>

            <div class="meta">
              Jumlah Item
              <strong>
                ${items.length} Item
              </strong>
            </div>

            <div class="slip-arrow">
              ⌄
            </div>

          </div>


          <div class="items">

            <table>

              <thead>

                <tr>
                  <th>No</th>
                  <th>Item Description</th>
                  <th>Short SKU</th>
                  <th>Qty Return</th>
                  <th>Aging Day</th>
                  <th>Dept.</th>
                </tr>

              </thead>

              <tbody>

                ${items.map((item, index) => `

                  <tr>

                    <td>
                      ${index + 1}
                    </td>

                    <td>
                      ${item.itemDesc}
                    </td>

                    <td>
                      ${item.shortSku}
                    </td>

                    <td>
                      ${Number(item.qty).toFixed(2)}
                    </td>

                    <td>
                      ${item.aging}
                    </td>

                    <td>
                      ${item.department}
                    </td>

                  </tr>

                `).join("")}

              </tbody>

            </table>

          </div>

        </div>

      `;

    });


  detailSection.innerHTML = `

    <button
      class="back-button"
      onclick="backToSupplier()"
    >
      ← Kembali ke daftar supplier
    </button>


    <div class="supplier-header">

      <div>

        <h2>
          ${supplier.name}
        </h2>

        <p>
          Kode Supplier: ${supplier.code}
        </p>

      </div>

      <div class="return-badge">
        ADA RETURN
      </div>

    </div>


    ${html}

  `;


  supplierSection.style.display = "none";

  detailSection.style.display = "block";


  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

}


/* =========================
   KEMBALI
========================= */

function backToSupplier(){

  detailSection.style.display =
    "none";

  supplierSection.style.display =
    "block";

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

}


/* =========================
   BUKA / TUTUP SLIP
========================= */

function toggleSlip(element){

  const card =
    element.parentElement;

  card.classList.toggle("open");


  const arrow =
    element.querySelector(".slip-arrow");


  if(arrow){

    arrow.textContent =
      card.classList.contains("open")
        ? "⌃"
        : "⌄";

  }

}


/* =========================
   SEARCH
========================= */

function searchSupplier(){

  const keyword =
    searchInput.value
      .trim()
      .toLowerCase();


  const filtered =
    RETURN_DATA.filter(row => {

      return (

        row.supplier
          .toLowerCase()
          .includes(keyword)

        ||

        String(row.supplierCode)
          .includes(keyword)

      );

    });


  renderSuppliers(filtered);

}


if(searchInput){

  searchInput.addEventListener(
    "input",
    searchSupplier
  );

}


/* =========================
   START
========================= */

renderSuppliers(RETURN_DATA);
